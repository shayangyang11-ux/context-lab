def check_answer(answer: str, keys: list[str]) -> bool:
    """归一化后做包含判断：答案需包含全部关键事实。"""
    norm = "".join(answer.split()).replace("／", "/").lower()
    return all("".join(k.split()).lower() in norm for k in keys)
